#!/usr/bin/env python3
"""Generate the browser's pre-catalog OCR engine fallback from the backend
roster — the OCR-list twin of sync_model_catalog.py.

Canonical sources: `OCR_ENGINE_TABLE` (frisket.contracts.actions.schemas._engines,
tier/label/billable for the symbolic local/sidecar/datalab engines) and
`ocr_vision_engines()` (derived from the shared `MODEL_ENTRIES` inventory in
frisket.server.action_catalog_hints for image-capable generic models). Both
feed `_recipe_engines`'s "ocr" branch, so this script and that function can
never see different data.

The symbolic table keeps its canonical order. Generic vision models are
inserted immediately before Datalab, matching `_recipe_engines`'s return list
(a projector parity test elsewhere pins dots.mocr to index 3).
Every OCR runtime is optional, so every fallback entry is unavailable until
the live catalog confirms that runtime — see engineCatalog.ts's
OCR_ENGINE_FALLBACK doc comment for the "honest pre-catalog placeholder"
rationale. OpenDocRouter models come from the runtime provider catalog,
so they have no frozen browser fallback list.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from frisket.contracts.actions.schemas._engines import OCR_ENGINE_TABLE
from frisket.server.action_catalog_hints import ocr_vision_engines

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "web/src/actions/engineCatalog.generated.ts"

PRE_CATALOG_ERROR = "Action catalog unavailable"


def render() -> str:
    table = {decl.id: decl for decl in OCR_ENGINE_TABLE}
    vision = {entry["id"]: entry for entry in ocr_vision_engines()}
    symbolic_order = [decl.id for decl in OCR_ENGINE_TABLE]
    datalab_index = symbolic_order.index("datalab")
    roster_order = [
        *symbolic_order[:datalab_index],
        *vision,
        *symbolic_order[datalab_index:],
    ]
    engines = []
    for engine_id in roster_order:
        if engine_id in table:
            decl = table[engine_id]
            label, tier, billable = decl.label, decl.tier, decl.billable
        else:
            entry = vision[engine_id]
            label, tier, billable = entry["label"], entry["tier"], entry["billable"]
        item: dict[str, object] = {"id": engine_id, "label": label, "tier": tier}
        if billable:
            item["billable"] = True
        if engine_id in vision:
            item["ocr_options"] = {"keep_text_position": True}
        item["available"] = False
        item["error"] = PRE_CATALOG_ERROR
        engines.append(item)
    body = json.dumps(engines, indent=2, ensure_ascii=False)
    return (
        "// Generated by scripts/dev/sync_ocr_engine_catalog.py from the canonical\n"
        "// OCR_ENGINE_TABLE (frisket.contracts.actions.schemas._engines) and\n"
        "// shared-catalog ocr_vision_engines() (frisket.server.action_catalog_hints). Do not edit\n"
        "// by hand.\n"
        "import type { EngineOption } from '../api/types';\n\n"
        f"export const OCR_ENGINE_FALLBACK_GENERATED = {body} satisfies EngineOption[];\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != output:
            raise SystemExit(
                "web OCR engine fallback is stale; run scripts/dev/sync_ocr_engine_catalog.py"
            )
        print(f"up to date: {OUT.relative_to(ROOT)}")
        return
    OUT.write_text(output)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
